README = (
    "ตารางคัดเลือกสื่อ: ระดับความสามารถ -> รหัสสื่อจากคู่มือทางการ | "
    "ทุกรหัสอ้างอิงจาก data/mediaCatalog2568.json (คู่มือรายการสิ่งอำนวยความสะดวก สื่อ บริการฯ "
    "พ.ศ. 2568 สำนักบริหารงานการศึกษาพิเศษ สพฐ.) ห้ามเพิ่มรายการที่ไม่มีรหัสในคู่มือ | "
    "สร้างโดย scripts/build_mapping.py — แก้ SELECTION ในสคริปต์แล้วรันใหม่ อย่าแก้ไฟล์นี้ด้วยมือ | "
    "สถานะ: rationale ยังไม่ผ่านการตรวจจากครูการศึกษาพิเศษ"
)


def main():
    catalog = {c["code"]: c for c in json.load(open(CATALOG, encoding="utf-8"))}

    out = {"_readme": README}
    errors, warnings, used = [], [], set()

    for dis_type, levels in SELECTION.items():
        out[dis_type] = {}
        for level, picks in levels.items():
            entries = []
            for code, rationale in picks:
                item = catalog.get(code)

                # ── ตรวจ 1: รหัสต้องมีอยู่จริงในคู่มือ ──
                if item is None:
                    errors.append(f"{dis_type}/{level}: ไม่พบรหัส {code} ในคู่มือ")
                    continue

                # ── ตรวจ 2: ประเภทความพิการต้องตรงกับสิทธิ์ในคู่มือ ──
                allowed = item["disabilityTypes"]
                if allowed and dis_type not in allowed:
                    warnings.append(
                        f"{dis_type}/{level}: {code} ({item['name'][:30]}) "
                        f"คู่มือระบุสิทธิ์เฉพาะ {allowed} — ต้องให้ครูยืนยัน"
                    )

                used.add(code)
                entries.append({
                    "code": code,
                    "item": item["name"],
                    "category": item["account"],     # บัญชี ก / ข / ค
                    "price": item["price"],          # None = บัญชี ก (ขอยืม ไม่มีราคา)
                    "mode": item["eligibilityMode"], # ขอรับ / ขอยืม / รับบริการ
                    "rationale": rationale,
                })
            out[dis_type][level] = entries

    json.dump(out, open(OUTPUT, "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    # ── รายงาน ──
    n_levels = sum(len(v) for k, v in out.items() if not k.startswith("_"))
    n_items = sum(len(e) for k, v in out.items() if not k.startswith("_")
                  for e in v.values())
    print(f"เขียน {OUTPUT}")
    print(f"  ประเภทความพิการ : {len(SELECTION)}")
    print(f"  ระดับความสามารถ : {n_levels}")
    print(f"  รายการสื่อ       : {n_items} (รหัสไม่ซ้ำ {len(used)})")

    if errors:
        print("\n❌ ERROR — รหัสไม่มีในคู่มือ (ต้องแก้ก่อนใช้งาน):")
        for e in errors:
            print("   ", e)
    if warnings:
        print("\n⚠️  WARNING — สิทธิ์ในคู่มือไม่ครอบคลุมประเภทนี้โดยตรง:")
        for w in warnings:
            print("   ", w)
    if not errors and not warnings:
        print("\n✅ ทุกรหัสมีอยู่จริงและตรงกับสิทธิ์ในคู่มือ")

    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
