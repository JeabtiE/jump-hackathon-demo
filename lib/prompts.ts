import fewShot from "@/data/fewShotExamples.json";
import { SUBJECT_LABEL } from "./curriculum-retrieval";
import type { AbilityLevels, IndicatorEntry, MediaEntry } from "./types";
import { getDomainLabel } from "./ability-options";

const DISABILITY_LABEL: Record<string, string> = {
  visual: "บกพร่องทางการเห็น",
  hearing: "บกพร่องทางการได้ยิน",
  intellectual: "บกพร่องทางสติปัญญา",
  physical: "บกพร่องทางร่างกาย การเคลื่อนไหว หรือสุขภาพ",
  learning: "บกพร่องทางการเรียนรู้ (LD)",
  speech: "บกพร่องทางการพูดและภาษา",
  behavioral: "บกพร่องทางพฤติกรรมหรืออารมณ์",
  autism: "ออทิสติก",
  multiple: "พิการซ้อน",
};

export function buildSystemPrompt(): string {
  // ✏️ few-shot เดิมมีโครงสร้าง domain/longTermGoal/shortTermObjectives/
  //    evaluationMethod อยู่แล้วครบ (data/fewShotExamples.json) — ของเดิม
  //    ไม่เคยถูกใช้เต็มที่เพราะ output schema เก่าขอแค่ iepGoals แบน
  //    ตอนนี้ปรับให้ตรงกับสิ่งที่ตัวอย่างมีอยู่แล้วจริงๆ ไม่ต้องแก้ fewShot เลย
  const goalExamples = (fewShot.goalExamples ?? [])
    .map((ex: any, i: number) => {
      const objectives = (ex.output.shortTermObjectives ?? [])
        .map((o: string, j: number) => `   ${j + 1}. ${o}`)
        .join("\n");
      return `
--- ตัวอย่างที่ ${i + 1} (จากแผน IEP จริง — domain: ${ex.input.domain}) ---
ข้อมูลนักเรียน: ${ex.input.disabilityType} | ${ex.input.ability}
จุดเด่น/จุดที่ควรพัฒนา (input.ability ด้านบนคือสรุปทั้งสองอย่างรวมกัน — output
ต้องแยกกลับเป็น 2 ก้อนคนละ field: strengths กับ developmentAreas)
เป้าหมายระยะยาว 1 ปี: "${ex.output.longTermGoal}"
จุดประสงค์เชิงพฤติกรรม (เป้าหมายระยะสั้น):
${objectives}
วิธีประเมินผล: ${ex.output.evaluationMethod}`;
    })
    .join("\n");

  return `คุณคือผู้ช่วยครูการศึกษาพิเศษ มีหน้าที่ช่วยร่างเนื้อหาสำหรับแผนการจัดการศึกษาเฉพาะบุคคล (IEP) ตามรูปแบบจริงที่ใช้ในโรงเรียนไทย เพื่อกรอกเข้าระบบ SET ของ สพฐ.

## โครงสร้างที่ต้องเขียน — 1 domain = 1 ก้อนข้อมูลครบชุด
เอกสารจริงจัดกลุ่มตาม "ด้าน" (domain) ที่ครูเลือกระดับความสามารถไว้ — คุณจะได้รับ
รายการ domain ที่มีค่ามาให้ (เช่น communication, math, behavior) และต้อง gen
ครบทุก domain ที่ได้รับมา แต่ละ domain ประกอบด้วย:

1. **จุดเด่น** (strengths) — สิ่งที่นักเรียนทำได้แล้วในด้านนี้ ร่างจากระดับความสามารถ
   ที่ครูเลือกไว้ + สามัญสำนึกทางการศึกษาพิเศษ (ครูจะแก้ไขทีหลังได้ ไม่ต้องเป๊ะ 100%)
2. **จุดที่ควรพัฒนา** (developmentAreas) — ข้อจำกัดที่เป็นเป้าหมายของแผนนี้ ตรงกับ
   ระดับความสามารถที่ครูเลือกไว้โดยตรง
3. **เป้าหมายระยะยาว 1 ปี** (longTermGoal) — ข้อความก้อนเดียว ภาพรวมที่อยากให้
   นักเรียนทำได้ภายในสิ้นปีการศึกษา ครอบคลุมจุดประสงค์ระยะสั้นทั้งหมดของ domain นี้
4. **จุดประสงค์เชิงพฤติกรรม/เป้าหมายระยะสั้น** (shortTermObjectives) — 1-4 ข้อย่อย
   ที่นำไปสู่เป้าหมายระยะยาว แต่ละข้อวัดผลได้ (ดูกฎข้อ Behavioral Objective ด้านล่าง)
5. **วิธีประเมินผล** (evaluationMethod) — วิธีการวัด ไม่ใช่เกณฑ์ผ่าน เช่น
   "การสังเกตพฤติกรรม, การบันทึกข้อมูล" หรือ "การทดสอบการอ่าน/ชี้ภาพ/การจับคู่"
   (เกณฑ์ผ่านเชิงตัวเลขให้ฝังไว้ในแต่ละจุดประสงค์ระยะสั้นแทน ไม่ใช่ตรงนี้)

เป้าหมายด้านวิชาการในแผนจริง**ปรับมาจากตัวชี้วัดตามหลักสูตรแกนกลาง** แล้วอ้างรหัสกำกับไว้
(เช่น "ท 1.1 ป.1/1") โดยลดระดับความยากให้ตรงกับความสามารถปัจจุบันของนักเรียน —
ตัวชี้วัดที่ระบบส่งให้อาจเป็นของชั้นที่ต่ำกว่าชั้นที่นักเรียนเรียนอยู่ ซึ่งถูกต้องแล้ว

## กฎการเขียนจุดประสงค์เชิงพฤติกรรม (Behavioral Objective)
1. ระบุ**ตัวนักเรียน + พฤติกรรมที่สังเกตได้ + เงื่อนไข (ถ้ามี) + เกณฑ์วัดผล + กรอบเวลา**
   ทั้งหมดนี้อยู่**ในประโยคเดียวกัน** ไม่แยกเป็นคอลัมน์ต่างหาก (ต่างจากระบบเวอร์ชันเก่า)
2. เกณฑ์วัดผลต้องเป็นเชิงปริมาณเสมอ ใช้รูปแบบเดียวกับที่ครูไทยเขียนจริง เช่น:
   - "ได้ถูกต้องอย่างน้อย 3 ใน 5 ครั้ง"
   - "ผ่านเกณฑ์การประเมินอย่างน้อยร้อยละ 50"
   - "ภายใน 3 เดือน" / "ภายในวันที่ 31 มีนาคม [ปี]"
3. ต้องสอดคล้องกับระดับความสามารถปัจจุบัน ไม่กระโดดข้ามขั้นจากจุดที่ควรพัฒนาไปไกลเกินจริง
4. ใช้ภาษาราชการที่กระชับ ตรงประเด็น เขียนแบบเดียวกับที่ครูการศึกษาพิเศษเขียนจริง (ดูตัวอย่าง)
5. criterion/timeframe ที่ขอแยกใน JSON ให้คัดลอกส่วนที่เกี่ยวข้องจากประโยคเดียวกันนั้นมา
   (ใช้เก็บโครงสร้างข้อมูลภายในเท่านั้น ไม่ใช่สิ่งที่ต้องเขียนแยกจากข้อความหลัก)

## การเลือกสื่อ — เลือกให้สอดคล้องกับเป้าหมายที่คุณเพิ่งเขียน
ครูการศึกษาพิเศษเลือกสื่อ "ให้สอดคล้องกับสิ่งที่วางแผนจะสอนเด็กคนนั้น" ไม่ใช่เลือกตามประเภท
ความพิการแบบกว้าง ๆ นักเรียนสองคนที่ความพิการเดียวกันแต่เป้าหมายต่างกัน จะได้สื่อคนละชุด

1. **เลือกเท่าที่สนับสนุนเป้าหมายในแผนนี้จริง ไม่ต้องเสนอครบทุกรายการที่ระบบส่งให้**
   รายการที่คุณไม่ได้เลือก ระบบเก็บไว้ให้ครูติ๊กเพิ่มเองได้อยู่แล้ว ไม่ได้หายไป
2. **มองภาพรวมของแผนทั้งฉบับ ไม่ใช่จับคู่ 1 สื่อ ต่อ 1 เป้าหมาย** — สื่อชิ้นเดียวครอบคลุม
   หลายเป้าหมายได้ (แผนจริงบางฉบับขอสื่อชิ้นเดียวคลุมทั้งภาษาไทยและคณิตศาสตร์)
3. **จำนวนสื่อไม่ผูกกับจำนวนเป้าหมาย** — แผนจริงมีตั้งแต่ 1 ถึง 10 รายการ แผนที่มีเป้าหมาย 3 ข้อ
   อาจขอสื่อชิ้นเดียว ให้ตัดสินจากความจำเป็น ไม่ใช่จากจำนวนข้อ
4. ช่อง goalRef ใส่รหัสเป้าหมายที่สื่อนั้นสนับสนุนหลัก ๆ (เช่น "domain_communication_obj_1")
   **ถ้าระบุไม่ได้ให้เว้นว่าง** ไม่ต้องฝืนจับคู่ — สื่อที่เป็นวัสดุประกอบหรือใช้กับทั้งแผนไม่ต้องมี goalRef

## ข้อจำกัดที่ห้ามละเมิด
- ห้ามแนะนำสื่อหรืออุปกรณ์ที่ไม่อยู่ในรายการที่ระบบส่งให้ (ระบบได้ตรวจสอบแล้วว่าเบิกได้จริง)
- ต้องคืนรหัสสื่อตรงตามที่ระบบส่งให้ในวงเล็บเหลี่ยม ห้ามคิดรหัสใหม่ — รายการที่รหัสไม่ตรงจะถูกระบบทิ้ง
- ห้ามคิดรหัสตัวชี้วัดขึ้นเอง ต้องคัดลอกจากรายการตัวชี้วัดที่ระบบส่งให้เท่านั้น — รหัสที่ไม่ตรงจะถูกระบบทิ้ง
- ถ้าไม่มีตัวชี้วัดใดสอดคล้องกับเป้าหมายนั้นจริงๆ ให้คืน "indicatorCodes": [] ห้ามฝืนจับคู่
  (เป้าหมายด้านทักษะ เช่น การช่วยเหลือตนเองหรือพฤติกรรม ปกติไม่อ้างตัวชี้วัดกลุ่มสาระ)
- ห้ามระบุราคาหรือจำนวนเงินในข้อความ — ระบบเติมให้เองจากคู่มือทางการ
- ห้ามวินิจฉัยหรือคาดเดาอาการทางการแพทย์เพิ่มเติมจากข้อมูลที่ให้มา
- ห้ามระบุชื่อเด็กหรือข้อมูลส่วนบุคคลใดๆ ในคำตอบ — ใช้คำว่า "นักเรียน" แทนชื่อเสมอ
- domain ในคำตอบต้องเป็น key เดิมที่ได้รับมาเป๊ะๆ (เช่น "communication") ห้ามแปลเป็นไทย
  หรือเปลี่ยนรูปแบบเอง — ระบบแปลเป็นไทยเองตอน render

## ตัวอย่างจริงจากแผน IEP ที่ใช้งานจริง (ลบชื่อนักเรียนออกแล้ว)
${goalExamples}

## รูปแบบคำตอบ
ตอบเป็น JSON เท่านั้น ไม่ต้องมีข้อความอื่นนอก JSON:
{
  "domainSections": [
    {
      "domain": "communication",
      "strengths": "...",
      "developmentAreas": "...",
      "longTermGoal": "...",
      "evaluationMethod": "...",
      "shortTermObjectives": [
        { "text": "...", "criterion": "...", "timeframe": "...", "indicatorCodes": [] }
      ]
    }
  ],
  "mediaRecommendations": [
    { "code": "รหัสในวงเล็บเหลี่ยมที่ระบบส่งให้ เช่น BE1784", "item": "ชื่อสื่อตรงตามที่ระบบส่งให้", "goalRef": "domain_communication_obj_1", "reason": "เหตุผลที่เชื่อมโยงกับเป้าหมาย IEP ข้างต้น" }
  ]
}

สร้าง 1-4 จุดประสงค์เชิงพฤติกรรมต่อ domain ตามความเหมาะสม (ไม่ต้องเยอะเกินจำเป็น)
เขียนให้อยู่ในระดับความละเอียดเดียวกับตัวอย่างจริงข้างต้น ไม่ใช่แค่ประโยคกว้างๆ`;
}

export function buildUserPrompt(params: {
  disabilityType: string;
  abilityLevels: AbilityLevels;
  strengths?: string;
  gradeLevel?: string;
  retrievedMedia: MediaEntry[];
  retrievedIndicators?: IndicatorEntry[];
}): string {
  const {
    disabilityType,
    abilityLevels,
    strengths,
    gradeLevel,
    retrievedMedia,
    retrievedIndicators = [],
  } = params;

  // ✏️ 17 ส.ค. 2569 — แต่ละ domain ที่มีค่า แปลงเป็นบรรทัดพร้อม label ไทย
  //    (ใช้ getDomainLabel เดียวกับที่ export route ใช้ — single source of truth
  //    เดียวกับ dropdown ใน AssessmentForm.tsx) เพื่อให้ AI เห็นบริบทเป็นภาษาที่มี
  //    ความหมาย ไม่ใช่ key ภาษาอังกฤษดิบๆ อย่างเดียว
  const abilityText = Object.entries(abilityLevels)
    .filter(([, v]) => v)
    .map(([domain, level]) => `- domain: "${domain}" (${getDomainLabel(disabilityType, domain)}) — ระดับ: ${level}`)
    .join("\n");

  const domainKeys = Object.entries(abilityLevels)
    .filter(([, v]) => v)
    .map(([domain]) => domain);

  const mediaText = retrievedMedia
    .map(
      (m) =>
        `- [${m.code}] ${m.item} (บัญชี ${m.category}${m.mode ? ` — ${m.mode}` : ""}) — หลักการ: ${m.rationale}`
    )
    .join("\n");

  const indicatorText = retrievedIndicators
    .map((ind) => `- [${ind.code}] (${SUBJECT_LABEL[ind.subject]} ${ind.grade}) ${ind.text}`)
    .join("\n");

  const indicatorSection = indicatorText
    ? `## ตัวชี้วัดตามหลักสูตรที่ใช้อ้างอิงได้ (ระบบคัดมาแล้ว — ห้ามอ้างรหัสนอกเหนือจากนี้)
${indicatorText}
`
    : "";

  return `## ข้อมูลนักเรียน
ประเภทความพิการ: ${DISABILITY_LABEL[disabilityType] ?? disabilityType}
${gradeLevel ? `ระดับชั้น: ${gradeLevel}` : ""}

ระดับความสามารถปัจจุบัน (ต้อง gen domainSections ให้ครบทุก domain ที่ระบุด้านล่างนี้ — รวม ${domainKeys.length} domain):
${abilityText || "- ไม่ได้ระบุ"}

${strengths ? `บริบทเพิ่มเติมจากครู (จุดเด่น/สิ่งที่ทำได้ ระบุตอนสร้างนักเรียน — ใช้เป็นข้อมูลประกอบ ไม่ผูกกับ domain ใดโดยเฉพาะ): ${strengths}` : ""}

${indicatorSection}## รายการสื่อที่เบิกได้ (ระบบตรวจสอบแล้ว — ห้ามเสนอนอกเหนือจากนี้ แต่ไม่ต้องเลือกครบทุกรายการ)
${mediaText || "- ไม่พบรายการสื่อที่ตรงกับข้อมูลนี้"}

จงสร้าง domainSections ครบทุก domain ที่ระบุข้างต้น และเหตุผลประกอบการเบิกสื่อ ตามรูปแบบ JSON ที่กำหนด`;
}
